# ══════════════════════════════════════════════════════════════════════
# ТИРИ
#
# Тири нашаровуються: v2 = v1 + своє, v3 = v2 + своє. Жоден тир не
# перевизначає файли нижчого, тому «встановити одразу v3» і «пройти
# v1 → v2 → v3» дають ІДЕНТИЧНИЙ результат — це властивість, яку
# перевіряє tests/test_tiers.py, а не побажання.
# ══════════════════════════════════════════════════════════════════════

def load_tiers() -> dict:
    if not TIERS_FILE.exists():
        raise SystemExit(f"ERROR: нема маніфесту тирів: {TIERS_FILE}")
    with TIERS_FILE.open("rb") as handle:
        return tomllib.load(handle)


def tier_table(manifest: dict | None = None) -> dict[str, dict]:
    return (manifest or load_tiers()).get("tier", {})


def tier_order(tier_id: str, manifest: dict | None = None) -> int:
    table = tier_table(manifest)
    if tier_id not in table:
        known = ", ".join(sorted(table, key=lambda t: table[t]["order"]))
        raise SystemExit(f"ERROR: невідомий тир {tier_id!r}. Відомі: {known}")
    return int(table[tier_id]["order"])


def tiers_upto(tier_id: str, manifest: dict | None = None) -> list[str]:
    """Кумулятивний список тирів від найнижчого до заданого."""
    manifest = manifest or load_tiers()
    table = tier_table(manifest)
    target = tier_order(tier_id, manifest)
    return sorted((t for t, v in table.items() if int(v["order"]) <= target),
                  key=lambda t: int(table[t]["order"]))


def tier_files(tier_id: str, manifest: dict | None = None) -> list[Path]:
    """Файли ОДНОГО тиру (без нижчих), що реально є в цьому чекауті."""
    manifest = manifest or load_tiers()
    found: set[Path] = set()
    for pattern in tier_table(manifest)[tier_id].get("paths", []):
        for path in KIT.glob(pattern):
            if path.is_file():
                found.add(path.relative_to(KIT))
    return sorted(found)


def resolve_files(tier_id: str, manifest: dict | None = None) -> list[Path]:
    """Кумулятивний набір файлів для тиру — те, що людина фактично отримує."""
    manifest = manifest or load_tiers()
    out: set[Path] = set()
    for tier in tiers_upto(tier_id, manifest):
        out.update(tier_files(tier, manifest))
    return sorted(out)


def tier_available(tier_id: str, manifest: dict | None = None) -> bool:
    """Чи фізично є цей шар у цій збірці (а не лише згадка про нього)."""
    manifest = manifest or load_tiers()
    meta = tier_table(manifest).get(tier_id, {})
    if meta.get("available") is False:
        return False
    return bool(meta.get("paths"))


def available_tiers(manifest: dict | None = None) -> list[str]:
    manifest = manifest or load_tiers()
    table = tier_table(manifest)
    return [t for t in sorted(table, key=lambda x: int(table[x]["order"]))
            if tier_available(t, manifest)]


def tier_of_file(rel: Path, manifest: dict | None = None) -> str | None:
    manifest = manifest or load_tiers()
    for tier in tier_table(manifest):
        if rel in set(tier_files(tier, manifest)):
            return tier
    return None


def now_slug() -> str:
    return dt.datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")


def as_path(value: str | Path) -> Path:
    return Path(value).expanduser().resolve()


def json_write(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)


def toml_string(value: str | Path) -> str:
    return json.dumps(str(value), ensure_ascii=False)


