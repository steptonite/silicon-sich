HOOK_MARKERS = {
    "claude": (Path.home() / ".claude" / "settings.json",
               ("pre_compact.sh", "session_start.sh", "semantic_recall.py")),
    "codex": (Path.home() / ".codex" / "hooks.json", ("codex_lifecycle.py",)),
}


def hooks_wired(agents: list[str] | None) -> dict:
    """Чи згадується хук кита у конфізі агента. None = не знаємо (нема конфіга)."""
    result: dict[str, bool | None] = {}
    for agent in (agents or ["claude", "codex"]):
        marker = HOOK_MARKERS.get(agent)
        if not marker:
            continue
        path, needles = marker
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            result[agent] = None
            continue
        result[agent] = any(needle in text for needle in needles)
    return result


def companion_hint() -> dict | None:
    """Одна доречна пропозиція супутника — або нічого. Ніколи не валить doctor."""
    script = KIT / "scripts" / "companions.py"
    if not script.exists():
        return None
    try:
        proc = subprocess.run([sys.executable, str(script), "--json"],
                              capture_output=True, text=True, timeout=15)
        return json.loads(proc.stdout) or None
    except Exception:
        return None


def install_dirs(root: Path) -> None:
    dirs = [
        "memory", "inbox/processed", "tasks/active", "tasks/archive",
        "external/raw", "external/source_cards", "external/distilled",
        "knowledge", "archives/chatgpt", "archives/gemini", "archives/claude",
        "archives/claude-code", "archives/codex", ".index", ".backups", ".sbkit",
    ]
    for rel in dirs:
        (root / rel).mkdir(parents=True, exist_ok=True)
    task_index = root / "tasks" / "_TASKS.md"
    if not task_index.exists():
        task_index.write_text(
            "# Tasks\n\n<!-- registry:start -->\n\n<!-- registry:end -->\n",
            encoding="utf-8",
        )


def detect_prior(root: Path) -> dict:
    """Що вже лежить у цьому корені. Ставити «поверх» безпечно тільки якщо
    ми чесно розуміємо, ЩО саме там лежить."""
    state = load_state(root)
    if state:
        return {"kind": "sbkit", "tier": state.get("tier", "v2"), "state": state}
    if not root.exists() or not any(root.iterdir()):
        return {"kind": "empty", "tier": None, "state": {}}
    # Вольт від безкоштовної версії: тека памʼяті/задач є, керуючого стану нема.
    markers = [root / "memory", root / "tasks", root / "inbox", root / "MEMORY.md"]
    if any(m.exists() for m in markers):
        return {"kind": "v1-vault", "tier": "v1", "state": {}}
    return {"kind": "foreign", "tier": None, "state": {}}


def cmd_install(args: argparse.Namespace) -> int:
    manifest = load_tiers()
    root = as_path(args.root)
    target = args.tier or manifest.get("default", "v2")
    tier_order(target, manifest)                      # валідація імені тиру
    prior = detect_prior(root)

    # 🔴 Пониження тиру нічого не «видаляє» — файли Кита лежать у чекауті, а не
    # у вольті. Але інструкція агента звузиться, і людина цього не очікує.
    if prior["tier"] and tier_order(target, manifest) < tier_order(prior["tier"], manifest) \
            and not args.allow_downgrade:
        raise SystemExit(
            f"ERROR: у {root} вже стоїть {prior['tier']}, а ти ставиш {target}.\n"
            "Дані не постраждають, але інструкція агента звузиться. "
            "Якщо це навмисно — додай --allow-downgrade."
        )

    config = as_path(args.config) if args.config else root / ".sbkit" / "config.toml"
    agents = ["claude", "codex"] if args.agent == "both" else [args.agent]
    previous = prior["state"]
    same = (previous.get("kit_version") == VERSION
            and previous.get("profile") == args.profile
            and previous.get("tier") == target)

    # Бекап перед будь-якою зміною — крім випадку, коли міняти нема чого.
    backup = None
    if not same and root.exists() and any(root.iterdir()):
        backup = create_backup(root)

    install_dirs(root)
    changed = False
    if not config.exists():
        changed |= write_if_changed(config, render_config(root, args.profile, target))
    if "claude" in agents:
        changed |= write_if_changed(
            root / "CLAUDE.md", adapter_text("CLAUDE.md.template", root, config, target))
    if "codex" in agents:
        try:
            changed |= write_if_changed(
                root / "AGENTS.md",
                adapter_text("AGENTS.md.template", root, config, target))
        except FileNotFoundError as exc:
            print(f"ℹ️ AGENTS.md не створено: {exc}")
    merged = sorted(set(previous.get("agents", [])) | set(agents))
    if merged != previous.get("agents", []):
        changed = True

    if same and not changed:
        print(json.dumps({"status": "already-installed", "tier": target,
                          "state": previous}, ensure_ascii=False, indent=2))
        return 0

    state = record_state(root, profile=args.profile, agents=merged,
                         config=config, backup=backup, tier=target)
    status = {"empty": "installed", "v1-vault": "adopted",
              "sbkit": "updated", "foreign": "installed"}[prior["kind"]]
    gained = ([] if prior["tier"] is None
              else [t for t in tiers_upto(target, manifest)
                    if tier_order(t, manifest) > tier_order(prior["tier"], manifest)])
    print(json.dumps({
        "status": status,
        "found_before": prior["kind"],
        "tier": target,
        "layers": tiers_upto(target, manifest),
        "layers_added_now": gained or tiers_upto(target, manifest),
        "files_active": len(resolve_files(target, manifest)),
        "backup": str(backup) if backup else None,
        "state": state,
    }, ensure_ascii=False, indent=2))
    return 0


def cmd_tiers(args: argparse.Namespace) -> int:
    manifest = load_tiers()
    table = tier_table(manifest)
    if args.verify:
        claimed: dict[Path, list[str]] = {}
        for tier in table:
            for rel in tier_files(tier, manifest):
                claimed.setdefault(rel, []).append(tier)
        infra: set[Path] = set()
        for section in ("infrastructure", "source_only"):
            for pattern in manifest.get(section, {}).get("paths", []):
                infra.update(q.relative_to(KIT) for q in KIT.glob(pattern) if q.is_file())
        tracked = subprocess.run(["git", "-C", str(KIT), "ls-files"],
                                 capture_output=True, text=True, check=False)
        problems = []
        for rel, tiers in sorted(claimed.items()):
            if len(tiers) > 1:
                problems.append(f"у кількох тирах ({', '.join(tiers)}): {rel}")
        if tracked.returncode == 0:
            for line in tracked.stdout.splitlines():
                rel = Path(line)
                if rel not in claimed and rel not in infra:
                    problems.append(f"не належить жодному тиру: {rel}")
        for problem in problems:
            print(f"🔴 {problem}")
        print(f"{'🔴' if problems else '✅'} файлів у тирах: {len(claimed)}, "
              f"інфраструктура: {len(infra)}, проблем: {len(problems)}")
        return 1 if problems else 0

    if args.available:
        print("/".join(available_tiers(manifest)))
        return 0
    if args.show_default:
        print(manifest.get("default") or available_tiers(manifest)[-1])
        return 0

    state = load_state(as_path(args.root)) if args.root else {}
    current = state.get("tier")
    for tier in sorted(table, key=lambda t: table[t]["order"]):
        meta = table[tier]
        mark = "▶" if tier == current else " "
        if not tier_available(tier, manifest):
            print(f"  {tier}  {meta['title']}  [не входить у цю збірку]")
            print(f"    {meta['promise']}")
            if meta.get("buy_url"):
                print(f"    → {meta['buy_url']}")
            continue
        access = "публічна" if meta.get("public") else "платна"
        print(f"{mark} {tier}  {meta['title']}  [{access}, файлів {len(tier_files(tier, manifest))}]")
        print(f"    {meta['promise']}")
    if current:
        print(f"\nЗараз у {as_path(args.root)}: {current} "
              f"(шари: {', '.join(tiers_upto(current, manifest))})")
    return 0


def cmd_demo(args: argparse.Namespace) -> int:
    owned_tmp = tempfile.TemporaryDirectory(prefix="sbkit-demo-") if not args.root else None
    root = as_path(args.root) if args.root else Path(owned_tmp.name)
    config = root / "config.toml"
    root.mkdir(parents=True, exist_ok=True)
    config.write_text(render_config(root, "guided"), encoding="utf-8")
    old_config = os.environ.get("SB_CONFIG")
    old_db = os.environ.get("LIBRARIAN_DB_PATH")
    os.environ["SB_CONFIG"] = str(config)
    os.environ["LIBRARIAN_DB_PATH"] = str(root / "demo.db")
    sys.path.insert(0, str(KIT / "scripts"))
    try:
        spec = importlib.util.spec_from_file_location("sbkit_demo_librarian", KIT / "scripts" / "librarian.py")
        if not spec or not spec.loader:
            raise RuntimeError("cannot load librarian")
        lib = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(lib)
        conn = lib.connect()
        samples = [
            ("memory", "/demo/canon.md", "У роботі з клієнтом використовуємо затверджений moodboard і дату рішення."),
            ("external", "/demo/article.md", "Зовнішня стаття радить зберігати всі референси без перевірки."),
            ("tasks", "/demo/task.md", "Підготувати moodboard для клієнта до п'ятниці."),
        ]
        import sqlite_vec
        for source, ref, text in samples:
            conn.execute(
                "INSERT INTO files(ref,source,sha,n_chunks,indexed_at,status) VALUES(?,?,?,?,?,?)",
                (ref, source, "demo", 1, 0, "active"),
            )
            rid = conn.execute(
                "INSERT INTO chunks(source,ref,chunk_idx,text) VALUES(?,?,0,?)",
                (source, ref, text),
            ).lastrowid
            conn.execute(
                "INSERT INTO vchunks(rowid,embedding) VALUES(?,?)",
                (rid, sqlite_vec.serialize_float32([0.0] * 1024)),
            )
        conn.commit()
        result = lib.search_index(
            conn, query="moodboard клієнта", qv=None, source=None, k=3,
            retrieval="keyword", max_per_file=2, after=None, before=None,
            include_undated=False, include_superseded=False, prefer_recent=False,
        )
        conn.close()
        print(json.dumps({"status": "ok", "root": str(root), "demo": result},
                         ensure_ascii=False, indent=2))
    finally:
        if old_config is None:
            os.environ.pop("SB_CONFIG", None)
        else:
            os.environ["SB_CONFIG"] = old_config
        if old_db is None:
            os.environ.pop("LIBRARIAN_DB_PATH", None)
        else:
            os.environ["LIBRARIAN_DB_PATH"] = old_db
        if owned_tmp:
            owned_tmp.cleanup()
    return 0


def migrate_text(text: str, root: Path, profile: str, tier: str = "v2") -> str:
    if re.search(r"(?m)^\[kit\]\s*$", text):
        text = re.sub(r'(?m)^version\s*=\s*".*?"$', f'version = "{VERSION}"', text, count=1)
        text = re.sub(r"(?m)^config_schema\s*=\s*\d+$",
                      f"config_schema = {CONFIG_SCHEMA}", text, count=1)
        if re.search(r"(?m)^tier\s*=", text):
            text = re.sub(r'(?m)^tier\s*=\s*".*?"$', f'tier = "{tier}"', text, count=1)
        else:
            text = re.sub(r"(?m)^(\[kit\]\s*)$", rf'\1\ntier = "{tier}"', text, count=1)
        return text
    header = (
        f"[kit]\nversion = \"{VERSION}\"\nconfig_schema = {CONFIG_SCHEMA}\n"
        f"data_schema = {DATA_SCHEMA}\nprofile = \"{profile}\"\ntier = \"{tier}\"\n\n"
    )
    text = header + text
    if not re.search(r"(?m)^external\s*=", text):
        text = re.sub(
            r'(?m)^(tasks\s*=\s*".*?"\s*)$',
            rf'\1\nexternal = "{root / "external"}"',
            text, count=1,
        )
    return text


def cmd_migrate(args: argparse.Namespace) -> int:
    if args.from_version != "v1":
        raise SystemExit("ERROR: only --from v1 is supported")
    source = as_path(args.source_config)
    root = as_path(args.root)
    target = as_path(args.config) if args.config else root / ".sbkit" / "config.toml"
    text = source.read_text(encoding="utf-8")
    changed = migrate_text(text, root, args.profile, args.tier)
    plan = {
        "from": str(source), "to": str(target), "root": str(root),
        "changes": ["add kit schema/version", "add external layer", "preserve existing paths"],
        "apply": args.apply,
    }
    if not args.apply:
        print(json.dumps(plan, ensure_ascii=False, indent=2))
        return 0
    backup = create_backup(root) if root.exists() and any(root.iterdir()) else None
    install_dirs(root)
    write_if_changed(target, changed)
    agents = ["claude", "codex"]
    write_if_changed(root / "CLAUDE.md",
                     adapter_text("CLAUDE.md.template", root, target, args.tier))
    write_if_changed(root / "AGENTS.md",
                     adapter_text("AGENTS.md.template", root, target, args.tier))
    record_state(root, profile=args.profile, agents=agents, config=target,
                 backup=backup, tier=args.tier)
    plan["backup"] = str(backup) if backup else None
    print(json.dumps(plan, ensure_ascii=False, indent=2))
    return 0


def cmd_backup(args: argparse.Namespace) -> int:
    root = as_path(args.root)
    archive = create_backup(root, as_path(args.destination) if args.destination else None)
    state = load_state(root)
    if state:
        state["last_backup"] = str(archive)
        json_write(state_path(root), state)
    print(archive)
    return 0


def cmd_restore(args: argparse.Namespace) -> int:
    root, archive = as_path(args.root), as_path(args.archive)
    before = restore_backup(root, archive, snapshot=not args.no_snapshot)
    state = load_state(root)
    if state:
        state["last_backup"] = str(archive)
        state["last_restore_undo"] = str(before) if before else None
        json_write(state_path(root), state)
    print(json.dumps({"restored": str(archive),
                      "pre_restore_backup": str(before) if before else None}, indent=2))
    return 0


def cmd_rollback(args: argparse.Namespace) -> int:
    root = as_path(args.root)
    state = load_state(root)
    archive = as_path(args.archive) if args.archive else (
        as_path(state["last_backup"]) if state.get("last_backup") else None
    )
    if archive is None:
        raise SystemExit("ERROR: no rollback backup recorded")
    before = restore_backup(root, archive, snapshot=True)
    restored = load_state(root)
    if restored:
        restored["last_backup"] = str(archive)
        restored["last_restore_undo"] = str(before)
        json_write(state_path(root), restored)
    print(json.dumps({"rolled_back_to": str(archive), "undo_backup": str(before)}, indent=2))
    return 0


def cmd_upgrade(args: argparse.Namespace) -> int:
    """Підняти версію Кита і/або тир. Обидва рухи — бекап-перший і ідемпотентні."""
    manifest = load_tiers()
    root = as_path(args.root)
    state = load_state(root)
    if not state:
        prior = detect_prior(root)
        hint = ("Схоже, це вольт безкоштовної версії — став поверх нього: "
                f"`python3 sbkit.py install --tier v2 --root {root}` "
                "(дані не чіпаються, робиться бекап)."
                if prior["kind"] == "v1-vault" else
                "Спершу `install`.")
        raise SystemExit(f"ERROR: у {root} нема стану Кита. {hint}")

    current = state.get("tier", "v2")
    target = args.to or current
    tier_order(target, manifest)
    if tier_order(target, manifest) < tier_order(current, manifest):
        raise SystemExit(
            f"ERROR: {current} → {target} — це пониження. "
            "Для нього є `install --tier ... --allow-downgrade`."
        )
    if state.get("kit_version") == VERSION and target == current:
        print(json.dumps({"status": "up-to-date", "version": VERSION, "tier": current},
                         ensure_ascii=False))
        return 0

    backup = create_backup(root)
    config = as_path(state["config"])
    profile = state.get("profile", "guided")
    write_if_changed(config,
                     migrate_text(config.read_text(encoding="utf-8"), root, profile, target))
    agents = state.get("agents", ["claude", "codex"])
    if "claude" in agents:
        write_if_changed(root / "CLAUDE.md",
                         adapter_text("CLAUDE.md.template", root, config, target))
    if "codex" in agents:
        write_if_changed(root / "AGENTS.md",
                         adapter_text("AGENTS.md.template", root, config, target))
    record_state(root, profile=profile, agents=agents, config=config,
                 backup=backup, tier=target)
    print(json.dumps({
        "status": "upgraded", "version": VERSION,
        "tier_from": current, "tier_to": target,
        "layers": tiers_upto(target, manifest),
        "files_active": len(resolve_files(target, manifest)),
        "backup": str(backup),
    }, ensure_ascii=False, indent=2))
    return 0


def cmd_update(args: argparse.Namespace) -> int:
    """Одна команда для того, у кого Кит УЖЕ стоїть: принести фікси, підняти стан,
    скласти СПИСОК ДІЙ і не дати про нього забути.

    Порядок обовʼязковий і саме такий: `upgrade` без `pull` відрапортує «up-to-date»
    і збреше — нові файли приносить лише git. Далі — головне: те, що приїхало,
    перетворюється на задачі, які висять у хуках, поки не будуть ЗРОБЛЕНІ
    (див. scripts/update_actions.py).
    """
    sys.path.insert(0, str(KIT / "scripts"))
    try:
        import update_actions as UA
    except ModuleNotFoundError:
        # Безкоштовний тир везе цей файл, але не везе примус застосування — і це
        # чесно: там оновлення підтягуються звичайним git pull, без черги задач.
        # Речення замість стектрейсу: людина має зрозуміти, що вона зробила не так.
        print(
            "ℹ️ Черга оновлень входить у платний тир.\n"
            "   Тут оновлення підтягуються так:  git pull --ff-only\n"
            "   Що змінилось — у CHANGELOG.md."
        )
        return 0

    if args.ack:
        print("✅ знято" if UA.ack(args.ack) else f"нема такої дії: {args.ack}")
        return 0
    if args.status:
        text = UA.notice()
        print(text or "✅ незастосованих оновлень немає")
        return 1 if text else 0

    def git(*a: str) -> subprocess.CompletedProcess:
        return subprocess.run(["git", "-C", str(KIT), *a], capture_output=True, text=True)

    if not (KIT / ".git").exists():
        raise SystemExit(
            "ERROR: твоя копія Кита — не git-репозиторій, оновлення приносити нічим.\n"
            "       Напиши автору: копію треба перевидати як репо, і далі оновлення "
            "стають однією командою."
        )
    dirty = git("status", "--porcelain").stdout.strip()
    if dirty:
        raise SystemExit(
            "ERROR: у теці Кита є власні зміни — оновлення зупинено, щоб їх не затерти.\n"
            f"{dirty[:400]}\n"
            "       🔴 Тека Кита має лишатись недоторканою: твої дані живуть у вольті, "
            "не тут.\n"
            "       Прибрати свої правки: git -C <кит> stash   (або git restore .)"
        )

    before = git("rev-parse", "HEAD").stdout.strip()
    pull = git("pull", "--ff-only")
    if pull.returncode != 0:
        raise SystemExit("ERROR: git pull не пройшов.\n" + (pull.stderr or pull.stdout).strip())
    after = git("rev-parse", "HEAD").stdout.strip()

    if before == after:
        print("✅ нових оновлень немає (копія вже на останньому стані)")
        left = UA.notice()
        if left:
            print("\n" + left)
            return 1
        return 0

    changed = [f for f in git("diff", "--name-only", before, after).stdout.split("\n") if f]
    commits = [c for c in git("log", "--oneline", f"{before}..{after}").stdout.split("\n") if c]

    root = as_path(args.root)
    upgraded = "пропущено"
    try:
        cmd_upgrade(argparse.Namespace(root=str(root), to=None))
        upgraded = "ok"
    except SystemExit as exc:  # стану немає — це не привід валити оновлення
        upgraded = str(exc)

    whats_new = root / ".sbkit" / "WHATS-NEW.md"
    whats_new.parent.mkdir(parents=True, exist_ok=True)
    data = UA.plan(changed, commits=commits, kit=KIT, whats_new=whats_new)
    whats_new.write_text(
        f"# Що приїхало {dt.datetime.now().strftime('%d.%m.%Y %H:%M')}\n\n"
        f"Кит: `{KIT}` · {before[:7]} → {after[:7]} · файлів змінено: {len(changed)}\n\n"
        "## Зміни\n" + "".join(f"- {c}\n" for c in commits) +
        "\n## Що треба зробити (це не список для читання — це задачі)\n" +
        "".join(f"- **[{a['id']}]** {a['why']}\n      `{a['command']}`\n"
                for a in data["actions"]) +
        "\n> Дії класу «замір» знімуться самі, коли стануть правдою. "
        "Дії класу «підтвердження» — лише `sbkit.py update --ack <id>`.\n",
        encoding="utf-8")

    print(f"⬇️  принесено: {len(commits)} змін, {len(changed)} файлів  ({before[:7]} → {after[:7]})")
    print(f"⬆️  стан Кита: {upgraded}")
    print(f"📄 що саме приїхало: {whats_new}")
    print()
    print(UA.notice() or "✅ дій не потрібно — оновлення суто текстове")
    return 1 if data["actions"] else 0


