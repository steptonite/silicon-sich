def state_path(root: Path) -> Path:
    return root / ".sbkit" / "state.json"


def load_state(root: Path) -> dict:
    path = state_path(root)
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def record_state(root: Path, *, profile: str, agents: list[str],
                 config: Path, backup: Path | None = None,
                 tier: str | None = None) -> dict:
    previous = load_state(root)
    tier = tier or previous.get("tier", "v2")
    operations = previous.get("operations", [])
    operations.append({"at": dt.datetime.now().astimezone().isoformat(),
                       "version": VERSION, "tier": tier})
    history = previous.get("tier_history", [])
    if not history or history[-1]["tier"] != tier:
        history.append({"tier": tier, "at": dt.datetime.now().astimezone().isoformat()})
    payload = {
        "kit_version": VERSION,
        "config_schema": CONFIG_SCHEMA,
        "data_schema": DATA_SCHEMA,
        "root": str(root),
        "config": str(config),
        "profile": profile,
        "tier": tier,
        "tier_history": history[-20:],
        "agents": sorted(set(agents)),
        "last_backup": str(backup) if backup else previous.get("last_backup"),
        "operations": operations[-50:],
    }
    json_write(state_path(root), payload)
    return payload


def checksum(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def create_backup(root: Path, destination: Path | None = None) -> Path:
    if not root.exists():
        raise SystemExit(f"ERROR: root does not exist: {root}")
    backup_dir = destination or root / ".backups"
    backup_dir.mkdir(parents=True, exist_ok=True)
    archive = backup_dir / f"sbkit-{now_slug()}.tar.gz"
    manifest: dict[str, str] = {}
    with tarfile.open(archive, "w:gz") as tar:
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(root)
            if rel.parts and rel.parts[0] in {".backups", ".index"}:
                continue
            manifest[str(rel)] = checksum(path)
            tar.add(path, arcname=Path("data") / rel, recursive=False)
        data = json.dumps(
            {"created": dt.datetime.now().astimezone().isoformat(),
             "root": str(root), "files": manifest},
            ensure_ascii=False, indent=2,
        ).encode("utf-8")
        info = tarfile.TarInfo("MANIFEST.json")
        info.size = len(data)
        tar.addfile(info, fileobj=__import__("io").BytesIO(data))
    return archive


def safe_members(tar: tarfile.TarFile) -> list[tarfile.TarInfo]:
    members = []
    for member in tar.getmembers():
        path = Path(member.name)
        if path.is_absolute() or ".." in path.parts:
            raise SystemExit(f"ERROR: unsafe archive member: {member.name}")
        members.append(member)
    return members


def restore_backup(root: Path, archive: Path, *, snapshot: bool = True) -> Path | None:
    if not archive.exists():
        raise SystemExit(f"ERROR: backup does not exist: {archive}")
    before = create_backup(root) if snapshot and root.exists() else None
    root.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "r:gz") as tar:
        members = safe_members(tar)
        for member in members:
            if not member.name.startswith("data/") or not member.isfile():
                continue
            rel = Path(member.name).relative_to("data")
            target = root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            source = tar.extractfile(member)
            if source is None:
                continue
            tmp = target.with_suffix(target.suffix + ".restore")
            with tmp.open("wb") as handle:
                shutil.copyfileobj(source, handle)
            tmp.replace(target)
    return before


def adapter_text(name: str, root: Path, config: Path, tier: str = "v2") -> str:
    """Інструкція для агента. Зростає разом із тиром — це і є різниця, яку
    агент фактично бачить: v3 додає йому обов'язок звіряти сказане із записаним."""
    base = KIT / "templates" / name
    if not base.exists():
        # 🔴 23.08.2026: у нижчому тирі шаблону може не бути. Раніше тут летів
        # FileNotFoundError посеред установки — людина отримувала стектрейс і
        # напів-поставлену базу. Відсутній шаблон означає «цього агента цей тир
        # не веде», а не «установка зламалась».
        raise FileNotFoundError(
            f"шаблон {name} не входить у тир {tier} — цього агента цей тир не веде"
        )
    parts = [base.read_text(encoding="utf-8")]
    for level in tiers_upto(tier):
        fragment = KIT / "templates" / f"tier-{level}.fragment.md"
        if fragment.exists():
            parts.append(fragment.read_text(encoding="utf-8"))
    text = "\n".join(part.rstrip() + "\n" for part in parts)
    return (text.replace("<KIT>", str(KIT)).replace("<ROOT>", str(root))
                .replace("<CONFIG>", str(config)).replace("<TIER>", tier))


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return True


def deps_present() -> dict:
    """Чи стоять залежності — у ТОМУ інтерпретаторі, яким кит реально працює.

    🔴 23.08.2026. Раніше тут стояв find_spec() у поточному процесі. Але install.sh
    запускає sbkit.py системним python3, а залежності ставить у .venv кита — тож
    бездоганно поставлена база рапортувала ready=false і радила «run: bash
    scripts/setup.sh», який людина щойно виконала. Новачок читає це як «зламалось»
    і йде питати автора. Міряти треба той python, який працюватиме, а не той,
    яким ми випадково запустились.
    """
    venv = KIT / ".venv" / "bin" / "python"
    if venv.exists():
        probe = ("import importlib.util as u,json;"
                 "print(json.dumps({m: u.find_spec(m) is not None "
                 "for m in ('sqlite_vec','numpy')}))")
        try:
            out = subprocess.run([str(venv), "-c", probe], capture_output=True,
                                 text=True, timeout=30)
            if out.returncode == 0:
                return json.loads(out.stdout.strip())
        except Exception:
            pass  # не змогли спитати .venv — падаємо до поточного процесу
    return {m: importlib.util.find_spec(m) is not None
            for m in ("sqlite_vec", "numpy")}


def cmd_doctor(args: argparse.Namespace) -> int:
    config = as_path(args.config) if args.config else None
    report = {
        "kit_version": VERSION,
        "platform": platform.platform(),
        "supported": sys.platform == "darwin" or sys.platform.startswith("linux"),
        "python": platform.python_version(),
        "python_ok": sys.version_info >= (3, 11),
        "git": shutil.which("git"),
        "ollama": False,
        **deps_present(),
        "config": str(config) if config else None,
        "config_ok": False,
        "issues": [],
    }
    try:
        urllib.request.urlopen("http://localhost:11434/api/tags", timeout=1)
        report["ollama"] = True
    except Exception:
        pass
    if not report["python_ok"]:
        report["issues"].append("Python 3.11+ required")
    if not report["supported"]:
        report["issues"].append("Windows/WSL is not supported in 2.0")
    if config:
        try:
            with config.open("rb") as handle:
                cfg = tomllib.load(handle)
            schema = int(cfg.get("kit", {}).get("config_schema", 1))
            report["config_ok"] = schema <= CONFIG_SCHEMA
            report["config_schema"] = schema
        except Exception as exc:
            report["issues"].append(f"invalid config: {exc}")
    if not report["sqlite_vec"] or not report["numpy"]:
        report["issues"].append(
            "залежності не стоять у .venv кита — полагодити: bash scripts/setup.sh")
    ready = (
        report["python_ok"] and report["supported"]
        and report["sqlite_vec"] and report["numpy"]
        and (not config or report["config_ok"])
    )
    report["ready"] = ready
    state: dict = {}
    try:
        manifest = load_tiers()
        state = load_state(as_path(args.root)) if getattr(args, "root", None) else {}
        report["tier"] = state.get("tier") or manifest.get("default")
        report["layers"] = tiers_upto(report["tier"], manifest)
        report["files_active"] = len(resolve_files(report["tier"], manifest))
    except SystemExit:
        report["tier"] = None
    hooks = hooks_wired(state.get("agents"))
    report["hooks"] = hooks
    for agent, wired in hooks.items():
        if wired is False:
            report["issues"].append(
                f"хуки для {agent} не підключені — компакт-щит і авто-пригадування "
                f"НЕ працюють, хоч файли стоять (див. docs/05-hooks.md, docs/18-codex-hooks.md)")
            ready = False
    report["ready"] = ready
    hint = companion_hint()
    if hint:
        report["companion"] = hint
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if ready else 1


